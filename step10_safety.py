"""Builds reports/safety_report.json and docs/model_card.md from measurements, not from assumptions.

1. Sanity sweep: how often does each field move the score in the direction a dispatcher would expect?
   (A finding, not a pass/fail: real collision data does not have to be monotone in every field.)
2. Fairness slices with Fairlearn on the 2025 replay: how the top 2% escalation is spread across areas.
3. Model facts copied from the model metadata so the card cannot drift from the deployed model.
"""
import itertools
import json

import numpy as np
import pandas as pd
from fairlearn.metrics import MetricFrame, selection_rate, true_positive_rate

import predict
from common import CHOICES, FLAG_RATE, POLICE_FORCE, REPLAY_PATH, ROOT, V2_META_PATH, VALID_SPEED

REPORTS = ROOT / "reports"
DOCS = ROOT / "docs"
BASE = dict(road_type="Single carriageway", weather="Fine, no high winds", light_condition="Daylight",
            junction_detail="Not at junction / roundabout / slip road")


def speed_sweep():
    """Raw score for each speed limit with everything else fixed, across contexts."""
    rows = []
    for road, light, area in itertools.product(["Single carriageway", "Dual carriageway", "Roundabout"],
                                               ["Daylight", "Darkness - lights lit"], ["1", "2"]):
        scores = [predict.raw_v2_score(predict.validate({**BASE, "road_type": road, "light_condition": light,
                                                         "urban_or_rural_area": area, "speed_limit": str(s)}))
                  for s in VALID_SPEED]
        rows.append(dict(road_type=road, light=light, area="Urban" if area == "1" else "Rural",
                         scores=[round(x, 4) for x in scores],
                         non_decreasing=bool(all(b >= a - 1e-9 for a, b in zip(scores, scores[1:])))))
    return rows


def fairness(replay):
    k = max(1, int(np.ceil(FLAG_RATE * len(replay))))
    cutoff = replay["raw_score"].nlargest(k).min()
    flagged = (replay["raw_score"] >= cutoff).astype(int)
    out = {}
    for name, column, labels in [("urban_or_rural_area", "urban_or_rural_area", {1: "Urban", 2: "Rural"}),
                                 ("police_force", "police_force", POLICE_FORCE)]:
        frame = replay.assign(group=replay[column].astype(str).map(lambda v: labels.get(int(float(v)), v) if name == "urban_or_rural_area" else labels.get(v, v)))
        counts = frame.group.value_counts()
        frame = frame[frame.group.isin(counts[counts >= 1500].index)]
        mf = MetricFrame(metrics={"escalated": selection_rate, "recall": true_positive_rate},
                         y_true=frame.target, y_pred=flagged.loc[frame.index], sensitive_features=frame.group)
        by = mf.by_group.round(4)
        out[name] = dict(
            groups=int(len(by)), recall_min=float(by.recall.min()), recall_max=float(by.recall.max()),
            recall_ratio=float(by.recall.min() / by.recall.max()), escalated_min=float(by.escalated.min()),
            escalated_max=float(by.escalated.max()),
            lowest_recall=[(str(g), float(v)) for g, v in by.recall.nsmallest(3).items()],
            highest_recall=[(str(g), float(v)) for g, v in by.recall.nlargest(3).items()])
    return out


def model_card(meta, sweep, fair):
    m = meta["metrics_final_test"]
    rises = sum(r["scores"][4] >= r["scores"][1] for r in sweep)
    falls_at_70 = sum(r["scores"][5] < r["scores"][4] for r in sweep)
    urb = fair["urban_or_rural_area"]
    return f"""# Model card: Call Severity Triage

Generated by `step10_safety.py` from the deployed model's metadata. Do not edit by hand.

## What it is
LightGBM classifier ({meta['tier']}, {len(meta['features'])} features) that estimates whether a road-traffic collision is
serious or fatal, from conditions known when the call is taken. Version `{meta['model_version']}`.

## What it is not
It is not a model of emergency-call outcomes. It was trained on STATS19 police-attended injury collisions, so it only
sees collisions that were recorded, with the severity recorded later. It must not replace dispatcher judgement.

## Evidence (trained on {meta['train_years'][0]}-{meta['train_years'][-2]}, tested once on {meta['test_year']})
| Measure | Value |
|---|---|
| Test calls | {int(m['n']):,} |
| Share serious or fatal | {m['base_rate']:.1%} |
| ROC AUC | {m['roc_auc']:.3f} |
| Precision in the top 2% | {m['P@2pct']:.1%} (95% interval {m['P@2pct_ci_low']:.1%} to {m['P@2pct_ci_high']:.1%}) |
| Gain over the speed-limit baseline | {m['diff_vs_level1_mean']*100:.1f} points (interval {m['diff_vs_level1_ci_low']*100:.1f} to {m['diff_vs_level1_ci_high']*100:.1f}) |

An AUC near {m['roc_auc']:.2f} is modest. Escalating the top 2% helps with ranking; it does not identify individual
serious collisions reliably.

## Behaviour checks
- Score stays between 0 and 1, is deterministic, ignores minutes within an hour, and treats blank optional fields as omitted
  (property tests in `test_safety.py`).
- Speed-limit sweep (everything else fixed): the score is higher at 60 mph than at 30 mph in {rises} of {len(sweep)}
  contexts, and drops again at 70 mph in {falls_at_70} of {len(sweep)}. The score is not monotone in the speed limit.
  This is what the data shows (70 mph roads are mostly motorways, where a smaller share of collisions is serious),
  so it is reported as a finding and not enforced as a rule. Full numbers are in `reports/safety_report.json`.

## Fairness slices (2025 replay, top 2% escalated nationally)
- Urban/rural recall: {urb['recall_min']:.1%} to {urb['recall_max']:.1%} (ratio {urb['recall_ratio']:.2f}).
- Police-force recall spans {fair['police_force']['recall_min']:.1%} to {fair['police_force']['recall_max']:.1%}
  across {fair['police_force']['groups']} forces with at least 1,500 test calls.
- Meaning: one national cutoff sends almost all escalations to rural areas and a few forces (Police Scotland most),
  and escalates almost nothing in urban areas. If each force has its own capacity, use a per-force cutoff
  (a quota of the top 2% inside each force) and report recall per force. Do not read the national figure as how
  well any one control room is served.
No single number makes a system fair. These are descriptive; differences can reflect real risk, reporting practice or both.

## Known limits
Recording practice differs by force; severity labels can change after the call; the model does not see vehicles,
casualties, time-critical symptoms or traffic volume.
"""


def main():
    REPORTS.mkdir(exist_ok=True)
    DOCS.mkdir(exist_ok=True)
    meta = json.loads(V2_META_PATH.read_text())
    replay = pd.read_csv(REPLAY_PATH)
    sweep, fair = speed_sweep(), fairness(replay)
    report = dict(speed_sweep=sweep, fairness=fair, model_version=meta["model_version"])
    (REPORTS / "safety_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    (DOCS / "model_card.md").write_text(model_card(meta, sweep, fair), encoding="utf-8")
    print("monotone contexts:", sum(r["non_decreasing"] for r in sweep), "of", len(sweep))
    print(json.dumps(fair, indent=2))


if __name__ == "__main__":
    main()
